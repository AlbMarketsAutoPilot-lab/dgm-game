// Step I-6.4: the approved rules together, and two ways to win a lifeline back by a choice.
// Usage: node tools/sim/i6-combo.mjs <board.json> [games=100000] [out.md]
import { readFileSync, writeFileSync } from "node:fs";
import { simulate } from "./engine.mjs";
import { APPROVED } from "./i6-setup.mjs";

const [, , path, gamesArg = "100000", out] = process.argv;
const board = JSON.parse(readFileSync(path, "utf8")), base = board.rulesR1R16 ?? board.rules ?? {}, N = Number(gamesArg);
const all = (t) => [t, t, t, t];
const sets = [
  ["0. Baseline (frozen R1–R16)", {}],
  ["Approved set", APPROVED],
  ["Approved + rest 3 turns = 1 lifeline", { ...APPROVED, lifeRest: 3 }],
  ["Approved + rest 2 turns = 1 lifeline", { ...APPROVED, lifeRest: 2 }],
  ["Approved + refuse a 20+ reward = 1 lifeline", { ...APPROVED, lifeRefuse: 20 }],
  ["Approved + rest 3 + no spending from square 190", { ...APPROVED, lifeRest: 3, lifeSpendUntil: 190 }],
  ["Approved + rest 3 + max 1 spend per game", { ...APPROVED, lifeRest: 3, lifeSpendMax: 1 }],
];

let md = `# Step I-6.4: the approved rules together — \`${board.id}\`\n\nGenerated by \`node tools/sim/i6-combo.mjs ${path} ${N}\` (seeded). 4 players, ${N.toLocaleString("en")} games per row.\n`;
md += `Approved set: waiting stairs, 3 lifelines, spend a lifeline to cancel a big punishment (never the last one), roadblock (game event), two roads.\n`;
md += `\n## 1. How the game feels\n\n"Simple" = every player takes the simple choice. "Thoughtful" = every player follows the written thoughtful rules.\n\n`;
md += `| Rules | Players | A Seats (win %) | Lead changes | Late overtakes | Close finishes | Win % first into last quarter | Win % last at half | Captures | C 10+ turns without moving | Turns lost | Players out | Lifelines spent / won back per game |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
let seed = 8000;
for (const [name, o] of sets) for (const t of name.startsWith("0.") ? ["simple"] : ["simple", "thoughtful"]) {
  if (t === "simple" && (o.lifeRest || o.lifeRefuse)) continue; // simple players never use these: same as the approved set
  const r = simulate(board, { ...base, ...o, types: all(t) }, N, seed++), e = r.excitement, b = r.boredom, x = r.i6, w = r.fairness.seatWinPct;
  md += `| ${name} | ${t} | ${Math.min(...w)}–${Math.max(...w)} | ${e.leadChanges} | ${e.lateOvertakes} | ${e.pctCloseFinish}% | ${e.winIfFirstIntoLastQuarter}% | ${e.winIfLastAtHalf}% | ${e.captures} | ${b.pctNoMove10}% | ${b.turnsLost} | ${x.pctPlayersOut}% | ${x.lifelinesSpentPerGame} / ${(x.lifelinesRestedPerGame + x.lifelinesRefusedPerGame).toFixed(2)} |\n`;
}

md += `\n## 2. Thinking target: one thoughtful player against 3 simple players (target 27–32%, fair 25%)\n\nRotated through all 4 seats, ${(N / 2).toLocaleString("en")} games per seat, ±${(196 * Math.sqrt(0.25 * 0.75 / (2 * N))).toFixed(2)} points (95%).\n\n`;
md += `| Rules | Thoughtful wins | Each simple player wins | Thoughtful out | Simple players out |\n|---|---|---|---|---|\n`;
for (const [name, o] of sets.slice(1)) {
  let w = 0, outT = 0, outAll = 0;
  for (let seat = 0; seat < 4; seat++) {
    const types = all("simple"); types[seat] = "thoughtful";
    const r = simulate(board, { ...base, ...o, types }, N / 2, seed++ * 10);
    w += r.fairness.seatWinPct[seat] / 4; outAll += r.i6.pctPlayersOut / 4; outT += r.i6.pctOutBySeat[seat] / 4;
  }
  const outS = (4 * outAll - outT) / 3;
  md += `| ${name} | **${w.toFixed(1)}%** | ${((100 - w) / 3).toFixed(1)}% | ${outT.toFixed(1)}% | ${outS.toFixed(1)}% |\n`;
}
if (out) writeFileSync(out, md);
console.log(md);
