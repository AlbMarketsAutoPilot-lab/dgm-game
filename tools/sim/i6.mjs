// Step I-6: measures each proposal on its own against the frozen baseline, and the thinking target.
// Usage: node tools/sim/i6.mjs <board.json> [games=100000] [out.md]
import { readFileSync, writeFileSync } from "node:fs";
import { simulate } from "./engine.mjs";

const [, , path, gamesArg = "100000", out] = process.argv;
const board = JSON.parse(readFileSync(path, "utf8")), base = board.rules ?? {}, N = Number(gamesArg);

// N3 two roads, tuned so that always taking the wild road is neither better nor worse (see the check below).
// Forks sit over the weakest stretches of the paper board (85, 90, 95 and 163-178). The safe road is the paper squares.
export const FORKS = [
  { at: 82, merge: 96, len: 13, tiles: { 2: { cat: "R", type: "jump", to: 100, text: "Wild road: shortcut over the hill" }, 5: { cat: "P", type: "jump", to: 30, then: "prison", text: "Wild road: lost, into the trap" } } },
  { at: 160, merge: 180, len: 19, tiles: { 3: { cat: "R", type: "jump", to: 185, text: "Wild road: shortcut over the hill" }, 7: { cat: "P", type: "jump", to: 30, then: "prison", text: "Wild road: lost, into the trap" } } },
];
const LIFE = { stairs: true, lifelines: 3 };
const all = (t) => [t, t, t, t];

const rows = [
  ["0. Baseline (frozen R1–R16)", {}],
  ["L1 Waiting stairs", { stairs: true }],
  ["L1 + 3 lifelines", LIFE],
  ["L1 + 3 lifelines, won back on 90, 118, 163", { ...LIFE, lifelineSquares: [90, 118, 163] }],
  ["N2 Roadblock (game event, back 10)", { roadblock: { back: 10, range: 10 } }],
  ["N3 Two roads, everyone takes the safe road", { forks: FORKS }],
  ["N3 Two roads, everyone takes the wild road", { forks: FORKS, types: all("wild") }],
  ["N3 Two roads, 4 thoughtful players", { forks: FORKS, types: all("thoughtful") }],
];

const res = rows.map(([name, o], i) => [name, simulate(board, { ...base, ...o }, N, 6000 + i)]);
const spread = (r) => { const w = r.fairness.seatWinPct; return `${Math.min(...w)}–${Math.max(...w)}`; };

let md = `# Step I-6 measurements — \`${board.id}\`\n\nGenerated by \`node tools/sim/i6.mjs ${path} ${N}\` (seeded, reproducible). 4 players, ${N.toLocaleString("en")} games per row. Rules tested in \`tools/sim/test/rules.test.mjs\`.\n`;
md += `\n## 1. Each proposal on its own\n\nTargets: A seats 24–26%; B excitement at least the baseline; C fewer than 5% of players with 10+ turns without moving.\n\n`;
md += `| Proposal | A Seats (win %) | Lead changes | Late overtakes | Close finishes | Win % first into last quarter | Win % last at half | Captures | C 10+ turns without moving | Turns lost | Players out | Extra |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
for (const [name, r] of res) {
  const e = r.excitement, b = r.boredom, x = r.i6;
  const extra = [x.stairStepsPerPlayer ? `stair steps/player ${x.stairStepsPerPlayer}` : "", x.lifelinesLostPerPlayer ? `lifelines lost/player ${x.lifelinesLostPerPlayer}` : "",
    x.lifelinesGainedPerPlayer ? `won back ${x.lifelinesGainedPerPlayer}` : "", x.roadblockHitsPerGame ? `roadblock hits/game ${x.roadblockHitsPerGame}` : "",
    x.wildPerGame || x.safePerGame ? `wild ${x.wildPerGame} / safe ${x.safePerGame} per game` : ""].filter(Boolean).join("; ");
  md += `| ${name} | ${spread(r)} | ${e.leadChanges} | ${e.lateOvertakes} | ${e.pctCloseFinish}% | ${e.winIfFirstIntoLastQuarter}% | ${e.winIfLastAtHalf}% | ${e.captures} | ${b.pctNoMove10}% | ${b.turnsLost} | ${x.pctPlayersOut}% | ${extra} |\n`;
}

// Thinking target: one player against 3 simple players, rotated through every seat.
const vs = (o, t, seed) => {
  let w = 0;
  for (let seat = 0; seat < 4; seat++) {
    const types = all("simple"); types[seat] = t;
    w += simulate(board, { ...base, ...o, types }, N / 2, seed + seat).fairness.seatWinPct[seat] / 4;
  }
  return w.toFixed(2);
};
const ci = (196 * Math.sqrt(0.25 * 0.75 / (2 * N))).toFixed(2);
const logic = [
  ["Baseline rules (only choice: the bonus card)", {}, "thoughtful"],
  ["N3 Two roads (bonus card + road choice)", { forks: FORKS }, "thoughtful"],
  ["L1 + 3 lifelines + N2 + N3 (all candidates together)", { ...LIFE, roadblock: { back: 10, range: 10 }, forks: FORKS }, "thoughtful"],
  ["Check: N3 player who ALWAYS takes the wild road", { forks: FORKS }, "wild"],
];
md += `\n## 2. Thinking target: one player against 3 simple players (target 27–32%, fair 25%)\n\nThe player is rotated through all 4 seats; ${(N / 2).toLocaleString("en")} games per seat; ±${ci} points (95%).\n\n| Rules | Win % of the one player |\n|---|---|\n`;
logic.forEach(([name, o, t], i) => { md += `| ${name} | ${vs(o, t, 7000 + 10 * i)}% |\n`; });

if (out) writeFileSync(out, md);
console.log(md);
