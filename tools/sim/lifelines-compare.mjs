// Compares lifeline versions for the owner's final choice (I-6), 2-4 players, short vs long games.
// Usage: node tools/sim/lifelines-compare.mjs <board.json> [games=100000] [out.md]
import { readFileSync, writeFileSync } from "node:fs";
import { simulate } from "./engine.mjs";
import { APPROVED } from "./i6-setup.mjs";

const [, , path, gamesArg = "100000", out] = process.argv;
const board = JSON.parse(readFileSync(path, "utf8")), N = Number(gamesArg);
const pc = (x) => (100 * x).toFixed(1) + "%", f1 = (x) => x.toFixed(1), f2 = (x) => x.toFixed(2);
const common = { ...board.rules, ...APPROVED, lifeOnTriple: false, outAfterZero: true };
const VERSIONS = [
  ["A", "−1 no 6 at Start/trap · +1 three 6s in a row", { ...common, lifeOnTriple: true }],
  ["B", "−1 no 6 at Start/trap · +1 a 6 that gets you out · −1 sent back to Start (captured or square 10)", { ...common, lifeOnEscape6: true, lifeOnCapture: true, lifeOnBackToStart: true }],
  ["B2", "same as B, but only captures cost a lifeline (square 10 does not)", { ...common, lifeOnEscape6: true, lifeOnCapture: true }],
];

let md = `# Lifelines: versions to choose from — \`${board.id}\`\n\nGenerated by \`node tools/sim/lifelines-compare.mjs ${path} ${N}\` (seeded). ${N.toLocaleString("en")} games per row group.\n`;
md += `All versions: frozen luck rules + waiting stairs, roadblock, two roads; 3 lifelines at the start; at 0 the player plays on ("Attention! You have no lifelines left…"), the 4th loss = out; no upper limit.\n\n`;
for (const [k, d] of VERSIONS.map(([k, d]) => [k, d])) md += `- **${k}:** ${d}\n`;
md += `\n"Short game" = fastest 25% of games, "long game" = slowest 25% (in rounds).\n`;
md += `\n## 1. Kicked out and lifelines left\n\n| Version | Players | Game | Players kicked out | …of them in rounds 1–10 | Games where someone is out | Players who see "Attention! no lifelines left" | Lifelines at the end (players still in) | Ends with 0 / 1 / 2 / 3 / 4+ | Won per player | Lost per player |\n|---|---|---|---|---|---|---|---|---|---|---|\n`;
const whole = [];
let seed = 7171;
for (const [key, , rules] of VERSIONS) for (const players of [2, 3, 4]) {
  const r = simulate(board, { ...rules, players, perGame: true }, N, seed++);
  if (players === 4) whole.push([key, r]);
  const recs = [...r.records].sort((a, b) => a.rounds - b.rounds), q = Math.floor(recs.length / 4);
  for (const [name, g] of [["all", recs], ["short", recs.slice(0, q)], ["long", recs.slice(-q)]]) {
    const ps = g.flatMap((x) => x.players), n = ps.length, sum = (fn) => ps.reduce((a, p) => a + fn(p), 0) / n;
    const outs = ps.filter((p) => p.out), alive = ps.filter((p) => !p.out), sh = (fn) => alive.filter(fn).length / alive.length;
    const dist = [0, 1, 2, 3].map((v) => pc(sh((p) => p.life === v))).join(" / ") + " / " + pc(sh((p) => p.life >= 4));
    md += `| ${key} | ${players} | ${name} | ${pc(outs.length / n)} | ${outs.length ? pc(outs.filter((p) => p.outRound <= 10).length / outs.length) : "–"} | ${pc(g.filter((x) => x.players.some((p) => p.out)).length / g.length)} | ${pc(ps.filter((p) => p.minLife <= 0).length / n)} | ${f1(alive.reduce((a, p) => a + p.life, 0) / alive.length)} | ${dist} | ${f2(sum((p) => p.gainTriple + p.gainEscape))} | ${f2(sum((p) => p.lostWait + p.lostCap + p.lostStart))} |\n`;
  }
}
md += `\n## 2. The whole game, 4 players\n\n| Version | Seats (win %) | Lead changes | Late overtakes | Close finishes | Captures | 10+ turns without moving |\n|---|---|---|---|---|---|---|\n`;
for (const [key, x] of [["Frozen baseline", simulate(board, { ...board.rules }, N, 7100)], ...whole]) {
  const e = x.excitement, w = x.fairness.seatWinPct;
  md += `| ${key} | ${Math.min(...w)}–${Math.max(...w)} | ${e.leadChanges} | ${e.lateOvertakes} | ${e.pctCloseFinish}% | ${e.captures} | ${x.boredom.pctNoMove10}% |\n`;
}
if (out) writeFileSync(out, md);
console.log(md);
