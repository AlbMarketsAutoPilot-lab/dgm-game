// Owner's final lifeline rules (I-6): 3 lifelines; -1 for 3 throws without a 6 at Start or in the trap;
// +1 for three 6s in a row in one turn; at 0 you play on ("Attention! no lifelines left"), the next loss = out.
// Usage: node tools/sim/lifelines-final.mjs <board.json> [games=100000] [out.md]
import { readFileSync, writeFileSync } from "node:fs";
import { simulate } from "./engine.mjs";
import { APPROVED } from "./i6-setup.mjs";

const [, , path, gamesArg = "100000", out] = process.argv;
const board = JSON.parse(readFileSync(path, "utf8")), N = Number(gamesArg);
const RULES = { ...board.rules, ...APPROVED };
const f1 = (x) => x.toFixed(1), f2 = (x) => x.toFixed(2), pc = (x) => (100 * x).toFixed(1) + "%";

let md = `# Lifelines, owner's final rules — \`${board.id}\`\n\nGenerated by \`node tools/sim/lifelines-final.mjs ${path} ${N}\` (seeded). ${N.toLocaleString("en")} games per number of players.\n`;
md += `Rules: frozen luck rules + waiting stairs, roadblock, two roads. **3 lifelines**; **−1** each time a player makes 3 throws without a 6 at Start or in the trap; **+1** for three 6s in a row in one turn; at 0 the player plays on ("Attention! You have no lifelines left…"); the **4th loss = out**. Captures cost nothing.\n`;
md += `"Short game" = fastest 25% of games, "long game" = slowest 25% (in rounds).\n`;
md += `\n## 1. Kicked out and lifelines left\n\n| Players | Game | Players kicked out | Games where someone is kicked out | Players who see "Attention! no lifelines left" | Lifelines at the end (players still in) | Ends with 0 / 1 / 2 / 3 / 4+ | Lost at Start / trap | Won (three 6s) |\n|---|---|---|---|---|---|---|---|---|\n`;
const fair = [];
for (const players of [2, 3, 4]) {
  const r = simulate(board, { ...RULES, players, perGame: true }, N, 6161 + players);
  fair.push([players, r]);
  const recs = [...r.records].sort((a, b) => a.rounds - b.rounds), q = Math.floor(recs.length / 4);
  for (const [name, g] of [["All games", recs], ["Short game", recs.slice(0, q)], ["Long game", recs.slice(-q)]]) {
    const ps = g.flatMap((x) => x.players), n = ps.length, avg = (k) => ps.reduce((a, p) => a + p[k], 0) / n;
    const alive = ps.filter((p) => !p.out), share = (fn) => alive.filter(fn).length / alive.length;
    const dist = [0, 1, 2, 3].map((k) => pc(share((p) => p.life === k))).join(" / ") + " / " + pc(share((p) => p.life >= 4));
    md += `| ${players} | ${name} | ${pc(ps.filter((p) => p.out).length / n)} | ${pc(g.filter((x) => x.players.some((p) => p.out)).length / g.length)} | ${pc(ps.filter((p) => p.minLife <= 0).length / n)} | ${f1(alive.reduce((a, p) => a + p.life, 0) / alive.length)} | ${dist} | ${f2(avg("lostWait"))} | ${f2(avg("gainTriple"))} |\n`;
  }
}
const base = (players) => simulate(board, { ...board.rules, players }, N, 6161 + players);
md += `\n## 2. The whole game with these rules vs the frozen baseline\n\n| Players | Rules | Seats (win %) | Lead changes | Late overtakes | Close finishes | Captures | 10+ turns without moving | Turns lost |\n|---|---|---|---|---|---|---|---|---|\n`;
for (const [players, r] of fair) for (const [name, x] of [["Baseline (frozen)", base(players)], ["Final", r]]) {
  const e = x.excitement, b = x.boredom, w = x.fairness.seatWinPct;
  md += `| ${players} | ${name} | ${w.join(" / ")} | ${e.leadChanges} | ${e.lateOvertakes} | ${e.pctCloseFinish}% | ${e.captures} | ${b.pctNoMove10}% | ${b.turnsLost} |\n`;
}
if (out) writeFileSync(out, md);
console.log(md);
