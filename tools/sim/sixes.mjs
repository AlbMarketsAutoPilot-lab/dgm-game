// How often a player throws one, two or three 6s in a row, and how often a player is sent back to Start by
// another player (capture), for 2-4 players, in short and long games.
// Usage: node tools/sim/sixes.mjs <board.json> [games=100000] [out.md]
import { readFileSync, writeFileSync } from "node:fs";
import { simulate } from "./engine.mjs";
import { APPROVED } from "./i6-setup.mjs";

const [, , path, gamesArg = "100000", out] = process.argv;
const board = JSON.parse(readFileSync(path, "utf8")), N = Number(gamesArg);
const f1 = (x) => x.toFixed(2), pc = (x) => (100 * x).toFixed(1) + "%";

let md = `# Sixes and captures per player — \`${board.id}\`\n\nGenerated by \`node tools/sim/sixes.mjs ${path} ${N}\` (seeded). ${N.toLocaleString("en")} games per row.\n`;
md += `Rules: the frozen luck rules + the approved I-6 rules (waiting stairs, 3 lifelines, roadblock, two roads), every player taking the simple choice.\n`;
md += `"Short game" = the fastest 25% of games, "long game" = the slowest 25% (counted in rounds). There is no short board yet.\n`;
md += `\n**Chance in one turn** (the first throws of the turn): one 6 = 1/6 = 16.7% · two 6s in a row = 1/36 = 2.8% · three 6s in a row = 1/216 = 0.46%.\n`;
md += `A turn counts here when the player throws the die (also at Start and in the trap); turns missed by "skip" squares do not count.\n`;

const rows = [];
for (const players of [2, 3, 4]) {
  const r = simulate(board, { ...board.rules, ...APPROVED, players, perGame: true }, N, 4242 + players);
  const recs = [...r.records].sort((a, b) => a.rounds - b.rounds), q = Math.floor(recs.length / 4);
  const groups = [["All games", recs], ["Short game", recs.slice(0, q)], ["Long game", recs.slice(-q)]];
  for (const [name, g] of groups) {
    const ps = g.flatMap((x) => x.players), n = ps.length, avg = (k) => ps.reduce((a, p) => a + p[k], 0) / n;
    const share = (fn) => ps.filter(fn).length / n;
    rows.push({ players, name, rounds: `${g[0].rounds}–${g[g.length - 1].rounds}`, roundsAvg: f1(g.reduce((a, x) => a + x.rounds, 0) / g.length),
      turns: f1(avg("throwTurns")), s1: f1(avg("six1")), s2: f1(avg("six2")), s3: f1(avg("six3")),
      s2any: pc(share((p) => p.six2 > 0)), s3any: pc(share((p) => p.six3 > 0)),
      cap: f1(avg("captured")), c0: pc(share((p) => p.captured === 0)), c1: pc(share((p) => p.captured === 1)), c2: pc(share((p) => p.captured === 2)), c3: pc(share((p) => p.captured >= 3)) });
  }
}
md += `\n## 1. Sixes per player per game\n\n| Players | Game | Rounds (range) | Rounds (average) | Turns with a throw | Turns starting with a 6 | …with two 6s in a row | …with three 6s in a row | Players with at least one double 6 | …at least one triple 6 |\n|---|---|---|---|---|---|---|---|---|---|\n`;
for (const x of rows) md += `| ${x.players} | ${x.name} | ${x.rounds} | ${x.roundsAvg} | ${x.turns} | ${x.s1} | ${x.s2} | ${x.s3} | ${x.s2any} | ${x.s3any} |\n`;
md += `\n## 2. Sent back to Start by another player (captured) per player per game\n\n| Players | Game | Times captured (average) | Never | Once | Twice | 3 times or more |\n|---|---|---|---|---|---|---|\n`;
for (const x of rows) md += `| ${x.players} | ${x.name} | ${x.cap} | ${x.c0} | ${x.c1} | ${x.c2} | ${x.c3} |\n`;
if (out) writeFileSync(out, md);
console.log(md);
