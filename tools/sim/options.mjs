// Measures small rule options against the boredom limit while keeping the family's start spacing.
// Usage: node tools/sim/options.mjs <board.json> [games=50000] [out.md]
import { readFileSync, writeFileSync } from "node:fs";
import { simulate } from "./engine.mjs";
const [, , path, gamesArg = "50000", out] = process.argv;
const board = JSON.parse(readFileSync(path, "utf8")), base = board.rules ?? {}, N = Number(gamesArg);
const opts = [
  ["Paper rules (enter only with 6, trap only with 6)", {}],
  ["No 6 needed to enter (for comparison)", { entry: "free" }],
  ["Enter with 6; after 3 failed tries you enter anyway", { enterAfter: 3 }],
  ["Enter with 6; after 2 failed tries you enter anyway", { enterAfter: 2 }],
  ["Enter with 1 or 6 (1: no extra throw)", { enterFaces: [1, 6] }],
  ["Trap: out with 6, or after 3 failed tries", { trapAfter: 3 }],
  ["Enter after 3 tries + trap after 3 tries", { enterAfter: 3, trapAfter: 3 }],
  ["Enter with 1 or 6 + trap after 3 tries", { enterFaces: [1, 6], trapAfter: 3 }],
];
let md = `# Rule options — \`${board.id}\`\n\nGenerated by \`node tools/sim/options.mjs ${path} ${N}\` (seeded). 4 players, ${N.toLocaleString("en")} games each. Target (GCD §11.3): fewer than 5% of players with 10+ turns without moving; seats within ±1 point.\n\n`;
md += `| Option | Players with 10+ turns without moving | Turns lost / player | Waiting to enter | Waiting in trap | Captures in squares 1–20 / game | Captures / game | Late overtakes / game | Close finishes | Win % first into last quarter | Win % by seat | Median rounds |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
opts.forEach(([name, o], i) => {
  const r = simulate(board, { ...base, ...o }, N, 5000 + i), b = r.boredom, e = r.excitement;
  md += `| ${name} | **${b.pctNoMove10}%** | ${b.turnsLost} | ${b.waitingToEnter} | ${b.waitingInTrap} | ${e.capturesEarly} | ${e.captures} | ${e.lateOvertakes} | ${e.pctCloseFinish}% | ${e.winIfFirstIntoLastQuarter}% | ${r.fairness.seatWinPct.join(" / ")} | ${r.length.median} |\n`;
});
if (out) writeFileSync(out, md);
console.log(md);
