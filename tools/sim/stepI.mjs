// Step I phase A3: the v3 rules on the Lantern Festival (data/lantern-festival.json), measured with tools/sim/engine3.mjs.
// Usage: node tools/sim/stepI.mjs [games] [out.md]   (default 100000 games per row; prints the tables)
import fs from "node:fs";
import { simulate3 } from "./engine3.mjs";

const GAMES = Number(process.argv[2] ?? 100000);
const OUT = process.argv[3];
const board = JSON.parse(fs.readFileSync(new URL("../../data/lantern-festival.json", import.meta.url)));

/** All seats of one type, or one `odd` player among `rest` (it sits on every seat in turn, GAMES / players each). */
function row(players, rest, odd = null) {
  if (!odd) return { r: simulate3(board, { players, types: Array(players).fill(rest) }, GAMES, 1), odd: null };
  const parts = [], per = Math.round(GAMES / players);
  let oddWins = 0;
  for (let seat = 0; seat < players; seat++) {
    const types = Array(players).fill(rest); types[seat] = odd;
    const r = simulate3(board, { players, types }, per, 100 + seat);
    oddWins += r.fairness.seatWinPct[seat] * r.games / 100;
    parts.push(r);
  }
  return { r: merge(parts), odd: +(100 * oddWins / parts.reduce((a, p) => a + p.games, 0)).toFixed(1) };
}

/** Averages the per-game measures of several runs (weighted by games). */
function merge(parts) {
  const n = parts.reduce((a, p) => a + p.games, 0);
  const avg = (get) => +(parts.reduce((a, p) => a + get(p) * p.games, 0) / n).toFixed(2);
  const walk = (get) => {
    const v = get(parts[0]);
    if (typeof v === "number") return avg(get);
    if (Array.isArray(v)) return v.map((_, i) => walk((p) => get(p)[i]));
    return Object.fromEntries(Object.keys(v).map((k) => [k, walk((p) => get(p)[k])]));
  };
  const out = walk((p) => ({ length: p.length, excitement: p.excitement, boredom: p.boredom, places: p.places, cards: p.cards, sixes: p.sixes }));
  return { games: n, capped: parts.reduce((a, p) => a + p.capped, 0), fairness: null, ...out };
}

const ROWS = [
  ["4 robots", row(4, "robot")],
  ["3 robots", row(3, "robot")],
  ["2 robots", row(2, "robot")],
  ["4 simple players", row(4, "simple")],
  ["1 robot among 3 simple", row(4, "simple", "robot")],
  ["1 simple among 3 robots", row(4, "robot", "simple")],
];

