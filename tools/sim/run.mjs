// Full measurement of a board under its rules + rule variants. Writes a markdown report.
// Usage: node tools/sim/run.mjs <board.json> [games=100000] [out.md]
import { readFileSync, writeFileSync } from "node:fs";
import { simulate } from "./engine.mjs";

const [, , path, gamesArg = "100000", out] = process.argv;
const board = JSON.parse(readFileSync(path, "utf8"));
const base = board.rules ?? {};
const N = Number(gamesArg);

const scenarios = [
  ["A. 4 players (board rules)", {}],
  ["B. 3 players", { players: 3 }],
  ["C. 2 players", { players: 2 }],
  ["D. 4p · sixes: standard (6,6,1 = 13)", { sixRule: "standard" }],
  ["E. 4p · entry: no 6 needed", { entry: "free" }],
  ["F. 4p · no capture", { capture: false }],
  ["G. 4p · END: any total reaching it", { endRule: "overshoot" }],
  ["H. 4p · bonus card used to attack the leader", { bonusPolicy: "attack" }],
  ["I. 4p · bonus card: whichever comes first", { bonusPolicy: "first" }],
];
const rows = scenarios.map(([name, set], i) => ({ name, ...simulate(board, { ...base, ...set }, N, 9000 + i) }));

const table = (title, head, fn) => {
  let t = `\n### ${title}\n\n| Scenario | ${head.join(" | ")} |\n|---|${head.map(() => "---").join("|")}|\n`;
  for (const x of rows) t += `| ${x.name} | ${fn(x).join(" | ")} |\n`;
  return t;
};

let md = `# Measurements — \`${board.id}\`\n\nGenerated by \`node tools/sim/run.mjs ${path} ${N}\` (seeded, reproducible). ${N.toLocaleString("en")} games per scenario.\nBoard rules: \`${JSON.stringify(base)}\`. Engine rules are tested in \`tools/sim/test/rules.test.mjs\`.\n`;
md += table("Group A — Fairness (win % by seat, turn order 1st → last)", ["Win % by seat", "±CI95"], (x) => [x.fairness.seatWinPct.join(" / "), x.fairness.ci95]);
md += table("Game length in rounds (reported, not a target)", ["Mean", "10% shortest ≤", "Median", "10% longest ≥"], (x) => [x.length.mean, x.length.p10, x.length.median, x.length.p90]);
md += table("Group B — Excitement: race", ["Lead changes / game", "Win % leader at half", "Win % last at half", "Comeback wins", "Late overtakes / game", "Games with late overtake", "Win % first into last quarter", "Close finishes (≤6)", "Avg finish gap"],
  (x) => { const e = x.excitement; return [e.leadChanges, e.winIfLeadingAtHalf + "%", e.winIfLastAtHalf + "%", e.comebackPct + "%", e.lateOvertakes, e.pctGamesLateOvertake + "%", e.winIfFirstIntoLastQuarter + "%", e.pctCloseFinish + "%", e.avgFinishGap]; });
md += table(`Group B — Excitement: big moments (jackpot/fall = jump of ${rows[0].excitement.bigJump}+ squares)`, ["Jackpots / game", "Falls / game", "Captures / game", "…in squares 1–20", "…in last quarter", "Games with a capture", "Players captured at least once"],
  (x) => { const e = x.excitement; return [e.jackpots, e.falls, e.captures, e.capturesEarly, e.capturesLate, e.pctGamesCapture + "%", e.pctPlayersCaptured + "%"]; });
md += table("Group C — Boredom (per player)", ["Turns lost", "…waiting to enter", "…waiting in trap", "Longest run without moving", "Players with 10+ turns without moving"],
  (x) => { const b = x.boredom; return [b.turnsLost, b.waitingToEnter, b.waitingInTrap, b.longestNoMove, b.pctNoMove10 + "%"]; });
md += table("Events (per player / per game)", ["Rewards hit", "Punishments hit", "Squares + by events", "Squares − by events", "Bonus defends / game", "Bonus attacks / game", "Jail passes used / game"],
  (x) => { const v = x.events; return [v.rewardsHit, v.punishmentsHit, v.squaresGained, v.squaresLost, v.bonusDefendPerGame, v.bonusAttackPerGame, v.jailPassPerGame]; });

md += `\n### Every event square (scenario A)\n\nLanded = % of players who land on it (and it takes effect) in a game. Win % if landed: fair is 25%. Impact = win % when the die put the player on the square minus win % when the die made them just miss it (first single-throw chance), in points.\n\n| Square | Cat | Text | Landed % | Win % if landed | Impact (pts) |\n|---|---|---|---|---|---|\n`;
for (const t of rows[0].tiles) md += `| ${t.tile} | ${t.cat} | ${t.title} | ${t.landedPct} | ${t.winIfLanded ?? "–"} | ${t.impact ?? "–"} |\n`;

if (out) writeFileSync(out, md);
console.log(md);
