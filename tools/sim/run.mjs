// Runs the v1 balance scenarios and writes a markdown report of raw results.
// Usage: node tools/sim/run.mjs <board.json> [games=100000] [out.md]
import { readFileSync, writeFileSync } from "node:fs";
import { loadBoard, simulate } from "./engine.mjs";

const [, , path, gamesArg = "100000", out] = process.argv;
const board = loadBoard(JSON.parse(readFileSync(path, "utf8")));
const N = Number(gamesArg);

const scenarios = [
  ["4p (board rules)", {}],
  ["3p", { players: 3 }],
  ["2p", { players: 2 }],
  ["4p · start: any roll", { startRule: "free" }],
  ["4p · start: needs a 6", { startRule: "need6" }],
  ["4p · END: exact roll", { endRule: "exact" }],
  ["4p · END: any roll reaching it", { endRule: "overshoot" }],
  ["4p · Tailwind off", { catchUp: 0 }],
  ["4p · Tailwind +2 for last place", { catchUp: 2 }],
];
const base = board.rules ?? {};
const rows = scenarios.map(([name, set], i) => ({ name, ...simulate(board, { ...base, ...set }, N, 1000 + i) }));

// Skill edge: one "smart" player (uses cards & choices well) vs casual players, rotated over all seats.
const skill = (extra) => {
  let w = 0;
  for (let seat = 0; seat < 4; seat++) {
    const policies = Array(4).fill("casual"); policies[seat] = "smart";
    w += simulate(board, { ...base, policies, ...extra }, N / 4, 2000 + seat).seatWinPct[seat];
  }
  return +(w / 4).toFixed(1);
};
const skillMain = skill({});

let md = `# Simulation results — \`${board.id}\`\n\nBoard rules: \`${JSON.stringify(base)}\`. Generated by \`node tools/sim/run.mjs ${path} ${N}\` (seeded, reproducible). ${N.toLocaleString("en")} games per scenario.\n\n`;
md += `| Scenario | Win % by seat | ±CI95 | Rounds mean / median / p90 | Turns lost / player | Boosts / Setbacks hit | Squares + / − | Longest no-move | ≥10-turn no-move | Lead changes | Win % leader at mid | Win % last at mid | Comeback |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
for (const x of rows) {
  const p = x.perPlayer, r = x.resilience;
  md += `| ${x.name} | ${x.seatWinPct.join(" / ")} | ${x.seatCI95} | ${x.rounds.mean} / ${x.rounds.median} / ${x.rounds.p90} | ${p.turnsLost} | ${p.boostsHit} / ${p.setbacksHit} | +${p.squaresGained} / −${p.squaresLost} | ${p.longestNoMove} | ${p.pctNoMove10}% | ${r.leadChanges} | ${r.winIfLeadingAtMid}% | ${r.winIfLastAtMid}% | ${r.comebackPct}% |\n`;
}
md += `\n### Excitement (big jump = ${rows[0].excitement.bigJumpSquares}+ squares)\n\n| Scenario | Jackpots / game | Falls / game | Games with a jackpot | Games with a fall | Late overtakes / game | Games with a late overtake | Win % of first into last quarter | Avg finish gap (squares) | Close finishes (≤ 6 squares) |\n|---|---|---|---|---|---|---|---|---|---|\n`;
for (const x of rows) {
  const e = x.excitement;
  md += `| ${x.name} | ${e.jackpotsPerGame} | ${e.fallsPerGame} | ${e.pctGamesWithJackpot}% | ${e.pctGamesWithFall}% | ${e.lateOvertakesPerGame} | ${e.pctGamesWithLateOvertake}% | ${e.winIfFirstIntoLastQuarter}% | ${e.avgFinishGap} | ${e.pctCloseFinish}% |\n`;
}
md += `\n**Skill edge** (one thoughtful player vs 3 casual players, fair = 25%): **${skillMain}%** (Stage 2 tooling; card/choice decisions only).\n`;
md += `\n## Tile impact (4p main scenario)\n\nImpact = win % when the die put the player on the tile minus win % when the die made them just miss it (first time within one roll). Fair win % is 25.\n\n| Tile | Cat | Type | Title | Landed by % of players | Impact (pts) |\n|---|---|---|---|---|---|\n`;
for (const t of rows[0].tiles) {
  const def = board.tiles[t.tile];
  md += `| ${t.tile} | ${t.cat} | ${t.type} | ${def.title ?? def.text ?? ""} | ${t.hitPct} | ${t.impactPts ?? "–"} |\n`;
}
if (out) writeFileSync(out, md);
console.log(md);
