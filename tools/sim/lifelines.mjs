// Owner idea (I-6): lifelines lost at Start / in the trap (3 throws without a 6) and when captured; +1 lifeline for every 6.
// Chance of being kicked out and lifelines left at the end, 2-4 players, short vs long games.
// Usage: node tools/sim/lifelines.mjs <board.json> [games=100000] [out.md]
import { readFileSync, writeFileSync } from "node:fs";
import { simulate } from "./engine.mjs";
import { APPROVED } from "./i6-setup.mjs";

const [, , path, gamesArg = "100000", out] = process.argv;
const board = JSON.parse(readFileSync(path, "utf8")), N = Number(gamesArg);
const f1 = (x) => x.toFixed(1), pc = (x) => (100 * x).toFixed(1) + "%";
const RULES = { ...APPROVED, lifeOnTriple: false, outAfterZero: false, lifeOnSix: true, lifeOnCapture: true }; // earlier idea, not the final rules

let md = `# Lifelines: lost at Start / trap and when captured, +1 for every 6 — \`${board.id}\`\n\nGenerated by \`node tools/sim/lifelines.mjs ${path} ${N}\` (seeded). ${N.toLocaleString("en")} games per number of players.\n`;
md += `Rules: frozen luck rules + waiting stairs, roadblock, two roads; 3 lifelines at the start; **−1** for 3 throws without a 6 at Start or in the trap; **−1** when sent back to Start by another player; **+1** for every 6 thrown; no upper limit; 0 lifelines = out.\n`;
md += `"Short game" = fastest 25% of games, "long game" = slowest 25% (in rounds).\n\n`;
md += `| Players | Game | Players kicked out | Games where someone is kicked out | Lifelines left at the end (players still in) | Middle half of players ends with | Won from 6s | Lost at Start / trap | Lost to captures |\n|---|---|---|---|---|---|---|---|---|\n`;
for (const players of [2, 3, 4]) {
  const r = simulate(board, { ...(board.rulesR1R16 ?? board.rules), ...RULES, players, perGame: true }, N, 5151 + players);
  const recs = [...r.records].sort((a, b) => a.rounds - b.rounds), q = Math.floor(recs.length / 4);
  for (const [name, g] of [["All games", recs], ["Short game", recs.slice(0, q)], ["Long game", recs.slice(-q)]]) {
    const ps = g.flatMap((x) => x.players), n = ps.length, avg = (k) => ps.reduce((a, p) => a + p[k], 0) / n;
    const alive = ps.filter((p) => !p.out).map((p) => p.life).sort((a, b) => a - b);
    const mid = `${alive[Math.floor(alive.length / 4)]}–${alive[Math.floor(alive.length * 3 / 4)]}`;
    md += `| ${players} | ${name} | ${pc(ps.filter((p) => p.out).length / n)} | ${pc(g.filter((x) => x.players.some((p) => p.out)).length / g.length)} | ${f1(alive.reduce((a, b) => a + b, 0) / alive.length)} | ${mid} | ${f1(avg("gainSix"))} | ${f1(avg("lostWait"))} | ${f1(avg("lostCap"))} |\n`;
  }
}
if (out) writeFileSync(out, md);
console.log(md);
