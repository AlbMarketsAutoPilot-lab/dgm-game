// "With vs without" runs: removes one event square at a time and measures how the game changes.
// Usage: node tools/sim/ablate.mjs <board.json> [games=20000] [out.md]
// A positive delta means the measure is HIGHER with the event than without it.
import { readFileSync, writeFileSync } from "node:fs";
import { simulate } from "./engine.mjs";

const [, , path, gamesArg = "20000", out] = process.argv;
const raw = JSON.parse(readFileSync(path, "utf8"));
const rules = raw.rules ?? {};
const N = Number(gamesArg), SEED = 777;

const measures = (r) => ({
  leadChanges: r.excitement.leadChanges,
  lateOvertakes: r.excitement.lateOvertakes,
  closeFinishPct: r.excitement.pctCloseFinish,
  firstIntoLastQWin: r.excitement.winIfFirstIntoLastQuarter,
  lastAtHalfWin: r.excitement.winIfLastAtHalf,
  captures: r.excitement.captures,
  turnsLost: r.boredom.turnsLost,
  noMove10Pct: r.boredom.pctNoMove10,
  seatSpread: +(Math.max(...r.fairness.seatWinPct) - Math.min(...r.fairness.seatWinPct)).toFixed(2),
});
const run = (tiles, seed) => measures(simulate({ ...raw, tiles }, rules, N, seed));

const base = run(raw.tiles, SEED);
const noise = run(raw.tiles, SEED + 1); // same board, other seed = size of random noise
const keys = Object.keys(base);
const fmt = (v) => (v > 0 ? "+" : "") + (+v.toFixed(2));

let md = `# With vs without each event — \`${raw.id}\`\n\nGenerated by \`node tools/sim/ablate.mjs ${path} ${N}\` (seeded). Rules: \`${JSON.stringify(rules)}\`. ${N.toLocaleString("en")} games per run, 4 players unless the rules say otherwise.\n\n`;
md += `Each row removes ONE event square (it becomes a plain square) and shows **with − without**. Positive = the event raises that measure.\n`;
md += `Excitement wants: lead changes ↑, late overtakes ↑, close finishes ↑, first-into-last-quarter win % ↓, last-at-half win % ↑ (captures: shown for information). Boredom wants: turns lost ↓, 10-turn waits ↓. Fairness: seat spread stays small.\n\n`;
md += `| Measure | ${keys.join(" | ")} |\n|---|${keys.map(() => "---").join("|")}|\n`;
md += `| **Board as is** | ${keys.map((k) => base[k]).join(" | ")} |\n`;
md += `| *Noise (same board, other seed: differences smaller than this are not meaningful)* | ${keys.map((k) => fmt(Math.abs(noise[k] - base[k]))).join(" | ")} |\n\n`;
md += `| Event square | Title | ${keys.join(" | ")} |\n|---|---|${keys.map(() => "---").join("|")}|\n`;

for (const k of Object.keys(raw.tiles).sort((a, b) => a - b)) {
  const t = raw.tiles[k];
  if (t.type === "place") continue;
  const { [k]: _, ...rest } = raw.tiles;
  const w = run(rest, SEED);
  md += `| ${k} | ${t.title ?? t.text} | ${keys.map((m) => fmt(base[m] - w[m])).join(" | ")} |\n`;
}
if (out) writeFileSync(out, md);
console.log(md);
