// Step I-5.1: the DRAFT short board built from the long board's events (proposal, not yet approved), measured with the
// options the owner must decide (fallen tree, one or two crossroads). The approved board will be data/board-short.json (I-5.2).
// Usage: node tools/sim/i5-draft.mjs [games=100000] [out.md]
import { readFileSync, writeFileSync } from "node:fs";
import { simulate } from "./engine.mjs";

const [, , gamesArg = "100000", out] = process.argv;
const N = Number(gamesArg);
const long = JSON.parse(readFileSync(new URL("../../data/board-long.json", import.meta.url), "utf8"));

// Kept long-board square -> [short-board square, new destination for a jump]. Every other long-board event is dropped.
export const KEEP = {
  15: [7], 20: [10, 16], 30: [15], 35: [17, 33], 40: [20, 51], 60: [30], 65: [32], 75: [37], 80: [40, 67],
  90: [45], 97: [49, 15], 108: [54, 67], 123: [61], 133: [66, 55], 138: [69, 97], 143: [72], 148: [74, 15], 158: [79, 24],
  183: [91, 48], 188: [94, 78], 193: [96, 92], 198: [99, 92], 202: [100, 82],
};
const fork = (at, merge, len, jSq, jTo, fSq) => ({ at, merge, len, tiles: {
  [jSq]: { cat: "R", type: "jump", to: jTo, text: "Wild road: shortcut over the hill" },
  [fSq]: { cat: "P", type: "jump", to: 15, then: "prison", text: "Wild road: lost, into the trap" } } });
const RIVER = fork(41, 48, 6, 1, 50, 2), CITY = fork(80, 90, 9, 1, 92, 3);

export function draft({ forks = [RIVER, CITY], roadblock = { back: 10, range: 10 } } = {}) {
  const tiles = {};
  for (const [L, [S, to]] of Object.entries(KEEP)) {
    const { story, icon, ...t } = long.tiles[L];
    tiles[S] = to === undefined ? t : { ...t, to };
  }
  return { id: "short-draft", lastTile: 100, endTile: 101, tiles, rules: { ...long.rules, roadblock, forks } };
}

const rows = [
  ["Long board (reference)", long],
  ["Draft: fallen tree 10/10 (unchanged), both crossroads", draft()],
  ["Draft: fallen tree halved (back 5, range 5)", draft({ roadblock: { back: 5, range: 5 } })],
  ["Draft: only the city crossroads (80)", draft({ forks: [CITY] })],
  ["Draft: only the river crossroads (41)", draft({ forks: [RIVER] })],
];
// R20 check: one player who always takes the Shortcut against 3 simple players, rotated through every seat.
const wild = (b, seed) => {
  let w = 0;
  for (let seat = 0; seat < 4; seat++) {
    const types = ["simple", "simple", "simple", "simple"]; types[seat] = "wild";
    w += simulate(b, { ...b.rules, types }, N / 2, seed + seat).fairness.seatWinPct[seat] / 4;
  }
  return w.toFixed(2) + "%";
};

let md = `# Step I-5.1: draft short board — measurements\n\nGenerated by \`node tools/sim/i5-draft.mjs ${N}\` (seeded). 4 players, ${N.toLocaleString("en")} games per row; Shortcut check: ${(N / 2).toLocaleString("en")} games per seat (±${(196 * Math.sqrt(0.1875 / (2 * N))).toFixed(2)} points).\n\n`;
md += `| Board | Seats (win %) | Lead changes | Win % leader at half | Win % last at half | Comeback wins | Late overtakes | Games with late overtake | Win % first into last quarter | Close finishes | Avg finish gap | Jackpots | Falls | Captures | Turns lost | 10+ turns without moving | Rounds (mean) | Always-Shortcut player wins |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
rows.forEach(([name, b], i) => {
  const r = simulate(b, b.rules, N, 4242), e = r.excitement, w = r.fairness.seatWinPct;
  md += `| ${name} | ${Math.min(...w)}–${Math.max(...w)} | ${e.leadChanges} | ${e.winIfLeadingAtHalf}% | ${e.winIfLastAtHalf}% | ${e.comebackPct}% | ${e.lateOvertakes} | ${e.pctGamesLateOvertake}% | ${e.winIfFirstIntoLastQuarter}% | ${e.pctCloseFinish}% | ${e.avgFinishGap} | ${e.jackpots} | ${e.falls} | ${e.captures} | ${r.boredom.turnsLost} | ${r.boredom.pctNoMove10}% | ${r.length.mean} | ${i ? wild(b, 9000) : "25.1% (I-6)"} |\n`;
});
md += `\nJackpot / fall = a jump of at least 10% of the board (long: 20 squares, short: 10). On the short board a fallen tree of 10 squares therefore counts as a fall.\n`;
if (out) writeFileSync(out, md);
console.log(md);
